// Command gen generates the constants of package security from the headers of
// the installed macOS SDK. Run it through go generate after Apple updates them.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

// valueConstants are values declared outside the "Value Constants" sections.
var valueConstants = map[string]bool{
	"kSecAttrSynchronizableAny": true,
	"kSecMatchLimitOne":         true,
	"kSecMatchLimitAll":         true,
}

var (
	enumRe       = regexp.MustCompile(`@enum\s+(.+?)\s*$`)
	externRe     = regexp.MustCompile(`^extern const CFStringRef (kSec\w+)`)
	deprecatedRe = regexp.MustCompile(`API_DEPRECATED(_WITH_REPLACEMENT)?\("([^"]*)"(.*)`)
	statusRe     = regexp.MustCompile(`^\s*(errSec\w+)\s+(.*?)=\s*(-?\d+|errSec\w+)\s*,?\s*(?:/\*\s*(.*?)\s*\*/)?\s*$`)
)

func main() {
	out, err := exec.Command("xcrun", "--show-sdk-path").Output()
	if err != nil {
		log.Fatal(err)
	}
	headers := filepath.Join(strings.TrimSpace(string(out)), "System/Library/Frameworks/Security.framework/Headers")
	write("symbols.go", symbols(read(filepath.Join(headers, "SecItem.h"))))
	write("errors.go", statuses(read(filepath.Join(headers, "SecBase.h"))))
}

func read(path string) []string {
	b, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	return strings.Split(string(b), "\n")
}

func write(name string, body string) {
	src := "// Code generated by internal/gen from the macOS SDK; DO NOT EDIT.\n\n//go:build darwin\n\npackage security\n\n" + body
	b, err := format.Source([]byte(src))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(name, b, 0o644); err != nil {
		log.Fatal(err)
	}
}

func goName(symbol string) string {
	return strings.TrimPrefix(symbol, "kSec")
}

func symbols(lines []string) string {
	var buf bytes.Buffer
	section := ""
	buf.WriteString("const (\n")
	for i := 0; i < len(lines); i++ {
		if m := enumRe.FindStringSubmatch(lines[i]); m != nil {
			section = m[1]
			fmt.Fprintf(&buf, "\n// %s\n", section)
			continue
		}
		m := externRe.FindStringSubmatch(lines[i])
		if m == nil {
			continue
		}
		symbol, decl := m[1], lines[i]
		for !strings.Contains(decl, ";") {
			i++
			decl += " " + strings.TrimSpace(lines[i])
		}
		if !onMacOS(decl) {
			continue
		}

		typ := "Key"
		if strings.Contains(section, "Value Constant") || valueConstants[symbol] {
			typ = "Constant"
		}
		d := deprecated(decl)
		if d != "" {
			fmt.Fprintf(&buf, "\n// %s is %s.\n//\n// Deprecated: %s\n", goName(symbol), symbol, d)
		}
		fmt.Fprintf(&buf, "%s %s = %q\n", goName(symbol), typ, symbol)
		if d != "" {
			buf.WriteString("\n")
		}
	}
	buf.WriteString(")\n")
	return buf.String()
}

func onMacOS(decl string) bool {
	if strings.Contains(decl, "macos(NA") || regexp.MustCompile(`API_UNAVAILABLE\([^)]*macos`).MatchString(decl) {
		return false
	}
	return strings.Contains(decl, "macos(") || !strings.Contains(decl, "API_")
}

func deprecated(decl string) string {
	m := deprecatedRe.FindStringSubmatch(decl)
	if m == nil || !strings.Contains(m[3], "macos(") {
		return ""
	}
	if m[1] != "" {
		return "Use " + goName(m[2]) + " instead."
	}
	return m[2]
}

func statuses(lines []string) string {
	var buf bytes.Buffer
	buf.WriteString("const (\n")
	for _, line := range lines {
		m := statusRe.FindStringSubmatch(line)
		if m == nil || m[1] == "errSecSuccess" {
			continue
		}
		name, value := "Err"+strings.TrimPrefix(m[1], "errSec"), m[3]
		if strings.HasPrefix(value, "errSec") {
			value = "Err" + strings.TrimPrefix(value, "errSec")
		}
		d := strings.Contains(strings.ToLower(m[2]), "deprecated")
		if d {
			fmt.Fprintf(&buf, "\n// %s is %s.\n//\n// Deprecated: Use %s instead.\n", name, m[1], value)
		}
		fmt.Fprintf(&buf, "%s Status = %s", name, value)
		if m[4] != "" {
			fmt.Fprintf(&buf, " // %s", m[4])
		}
		buf.WriteString("\n")
		if d {
			buf.WriteString("\n")
		}
	}
	buf.WriteString(")\n")
	return buf.String()
}
